from __future__ import annotations

import argparse

from .. import stats
from ..config import INFRA, RUNTIMES, TERMINALS
from .setup import guide_names


FORCE_HELP = "overwrite files that exist; a file you changed is first saved next to it as NAME.bak"


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="dah", description="Control tower and review board for AI agent lanes.")
    from .. import __version__
    ap.add_argument("--version", action="version", version=f"dah {__version__}")
    ap.add_argument("--as", dest="as_", metavar="LANE", help="act as this lane (default: $TOWER_LANE)")
    sub = ap.add_subparsers(dest="cmd", required=True, metavar="COMMAND")

    sub.add_parser("mine", help="your task and its items")
    p = sub.add_parser("item", help="post or fix a board item")
    isub = p.add_subparsers(dest="sub", required=True)
    for name in ("add", "update"):
        q = isub.add_parser(name)
        if name == "update":
            q.add_argument("id", type=int)
        q.add_argument("--title", required=name == "add")
        q.add_argument("--body")
        q.add_argument("--body-file")
        q.add_argument("--option", action="append", default=[], metavar="LABEL=MEANING")
        q.add_argument("--recommend", metavar="LABEL", help="the option you recommend; the board shows it first")
        q.add_argument("--attach", action="append", default=[], metavar="PATH")
        if name == "add":
            q.add_argument("--kind", choices=("decision", "review"))
            q.add_argument("--multi", action="store_true", help="several options may be picked")
            q.add_argument("--to", metavar="MEMBER", help="the one person who sees the card (with `requester` on, "
                           "the default is whoever asked for the work); `all` = everyone")
            q.add_argument("--request", type=int, metavar="MEMO_ID", help="hub: the board request this card answers "
                           "(its sender gets the card)")
    q = isub.add_parser("merge")
    q.add_argument("id", type=int)
    q.add_argument("--into", type=int, required=True)

    p = sub.add_parser("report", help="team lanes: done | blocked | note | handoff; everyone: wrapped")
    p.add_argument("kind", choices=("done", "blocked", "note", "handoff", "wrapped"))
    p.add_argument("text")
    p.add_argument("--attach", action="append", default=[])

    p = sub.add_parser("task", help="hub: queue a task for a team lane")
    p.add_argument("lane")
    p.add_argument("--title", required=True)
    p.add_argument("--goal", type=int, metavar="GOAL_ID", help="removed in 0.8.0; ignored with a notice")
    p.add_argument("--deliverable", metavar="KEY", help="deliverable key (e.g. ui:shop): ties the tasks that rework the same deliverable together")
    p.add_argument("--request", type=int, metavar="MEMO_ID", help="the board request this task serves: its sender "
                   "is the requester")
    p.add_argument("--for", dest="for_", metavar="MEMBER", help="the requester by name; `all` = nobody in particular")
    p.add_argument("brief")
    p = sub.add_parser("task-bump", help="hub: move a queued team task to the front (typed `dah task bump ID`)")
    p.add_argument("id", type=int)
    p = sub.add_parser("blame", help="lane: name the stage that should have caught this task's failure; hub: --confirm [STAGE]")
    p.add_argument("stage", nargs="?", help="stage number or name, e.g. 3")
    p.add_argument("--task", type=int)
    p.add_argument("--cause", help="one line")
    p.add_argument("--confirm", action="store_true", help="hub: confirm (or change to STAGE) the lane's blame on --task")
    p = sub.add_parser("deliverable", help="hub/infra: record the human's result (adopted|redirected|dropped); with no result, the lineage")
    p.add_argument("key")
    p.add_argument("outcome", nargs="?", choices=("adopted", "redirected", "dropped"))
    p.add_argument("--note", help="redirected: the human's own words")
    p = sub.add_parser("ratings", help="first-pass rate per stage and process, bars, token cost per attempt and per adopted deliverable")
    p.add_argument("--engine")
    p.add_argument("--lane")
    p.add_argument("--weak", action="store_true", help="only rows that need fixing or rework")
    p = sub.add_parser("doing", help="hub: one line shown on the board")
    p.add_argument("text")
    p = sub.add_parser("scratch", help="lane: a scratch folder outside the project, removed after your task closes")
    p.add_argument("--worktree", action="store_true", help="a detached git worktree of your HEAD instead of an empty folder")
    p = sub.add_parser("paths", help="lane: declare the files and folders your task will change (a file lock between "
                                     "sessions of one lane); hub: --task N sets them on a queued task")
    p.add_argument("paths", nargs="+")
    p.add_argument("--task", type=int, help="hub: a queued task")
    p = sub.add_parser("stage", help="lane: name the stage of your process card you are on now (shown on the board)")
    p.add_argument("stage", help="stage number or name, e.g. 3")
    p = sub.add_parser("tell", help="hub: message a running task")
    p.add_argument("lane")
    p.add_argument("text")
    p.add_argument("--urgent", action="store_true",
                   help="reach a busy Claude Code lane at its next tool call, mid-turn (e.g. \"stop\"); dropped after 2 h")
    p = sub.add_parser("wrap", help="hub: ask a lane to wrap up")
    p.add_argument("lane")
    p.add_argument("--note")
    p = sub.add_parser("decide", help="hub: decide an item within approved scope")
    p.add_argument("id", type=int)
    p.add_argument("verdict", choices=("ok", "no", "hold"))
    p.add_argument("--choice", action="append")
    p.add_argument("--note")
    p.add_argument("--basis")
    p = sub.add_parser("escalate", help="hub: send an item to humans")
    p.add_argument("id", type=int)
    p.add_argument("--why", required=True)
    p.add_argument("--to", metavar="MEMBER", help="with `requester` on, the default is the person the card is for; "
                   "`all` = everyone")
    p = sub.add_parser("cancel", help="hub: cancel a task")
    p.add_argument("task", type=int)
    p = sub.add_parser("memo", help="hub/infra: reply, forward or send memos")
    msub = p.add_subparsers(dest="sub", required=True)
    q = msub.add_parser("reply")
    q.add_argument("id", type=int)
    q.add_argument("text")
    q = msub.add_parser("bump", help="hub: move a waiting infra memo or decision to the front of the infra queue")
    q.add_argument("id", type=int)
    q = msub.add_parser("forward")
    q.add_argument("id", type=int)
    q = msub.add_parser("paths", help="infra: declare the paths of the message this session holds (a file lock); "
                                      "hub: a hint on a waiting one")
    q.add_argument("id", type=int)
    q.add_argument("paths", nargs="*")
    q.add_argument("--alone", action="store_true", help="runs with no other infra session (a reinstall, a restart)")
    q = msub.add_parser("send")
    q.add_argument("target", choices=(INFRA,))
    q.add_argument("text")
    q.add_argument("--approved", metavar="CITE", help="the human's approval: a request number or their words")
    q.add_argument("--paths", metavar="A,B", help="a hint: files or folders it will touch (the session declares its own)")
    q.add_argument("--alone", action="store_true", help="it must run with no other infra session (a reinstall)")
    p = sub.add_parser("infra", help="hub: ask infra to do something (infra runs only on a hub request)")
    p.add_argument("text")
    p.add_argument("--approved", metavar="CITE", help="the human's approval: a request number or their words")
    p.add_argument("--paths", metavar="A,B", help="a hint: files or folders it will touch, comma separated. The infra "
                   "session declares its own paths when it starts (a file lock); without a hint it still starts")
    p.add_argument("--alone", action="store_true", help="it must run with no other infra session (a reinstall, a restart)")
    p.add_argument("--model", help="the model its infra session opens with (fable, opus, sonnet, haiku or a full id); "
                   "a `model:` line in the text does the same. Default: the infra lane's own")
    p.add_argument("--effort", help="low|medium|high|xhigh|max for its infra session; an `effort:` line does the same")

    sub.add_parser("status", help="lanes, tasks and open items")
    p = sub.add_parser("stats", help="the task ledger: tokens, turns and rework per lane, engine, model, effort or week")
    p.add_argument("--by", choices=stats.BY, default="lane")
    p.add_argument("--lane")
    p.add_argument("--since", metavar="YYYY-MM-DD")
    p = sub.add_parser("retros", help="what lanes noted when they wrapped (cost, corrected, rule)")
    p.add_argument("--lane")
    p.add_argument("--since", metavar="YYYY-MM-DD")
    p = sub.add_parser("signal")  # called by a lane's own hooks in a terminal window; not for people
    p.add_argument("payload", nargs="*")
    p = sub.add_parser("show", help="one board item")
    p.add_argument("id", type=int)
    p = sub.add_parser("items", help="list board items")
    p.add_argument("--open", action="store_true")
    p.add_argument("--lane")
    p.add_argument("-n", type=int, default=50)
    p = sub.add_parser("tasks", help="list tasks")
    p.add_argument("--all", action="store_true")
    p = sub.add_parser("log", help="a task's brief and reports")
    p.add_argument("task", type=int)
    p = sub.add_parser("last", help="a lane's last words")
    p.add_argument("lane")
    p.add_argument("-n", type=int, default=1)

    p = sub.add_parser("run", help="run the tower in the foreground (loop + board)")
    p.add_argument("--no-hub", action="store_true", help="do not keep the hub running")
    sub.add_parser("start", help="run the tower in the background")
    sub.add_parser("restart", help="restart the tower loop on the current code (lane sessions keep running)")
    p = sub.add_parser("stop", help="stop the background tower")
    p.add_argument("--close-lanes", action="store_true")
    sub.add_parser("pause", help="stop driving lanes (the board keeps working)")
    sub.add_parser("resume", help="drive lanes again")

    p = sub.add_parser("discover", help="survey agents, configs, MCP servers and hosting tools (JSON, no secrets)")
    p.add_argument("--project")
    p = sub.add_parser("init", help="create .tower/ in this workspace")
    p.add_argument("--home", help="workspace folder (default: here)")
    p.add_argument("--name", default="Agent Hub")
    p.add_argument("--lang", default="en", help="language people read the board in: en, ko, ja, zh, es, ... (default en)")
    p.add_argument("--hub", choices=RUNTIMES)
    p.add_argument("--infra", choices=RUNTIMES)
    p.add_argument("--project", help="folder agents work in, relative to the workspace (default: the workspace)")
    p.add_argument("--safe", action="store_true", help="sandboxed agent permissions instead of unattended ones")
    p.add_argument("--terminal", choices=TERMINALS, default="none",
                   help="where lane sessions run: none (in the background, the default), tmux or orca (windows the "
                        "tower opens and closes, which people can watch)")
    p.add_argument("--force", action="store_true", help=FORCE_HELP)
    p = sub.add_parser("install", help="(re)write protocol, lane files and command shims")
    p.add_argument("--force", action="store_true", help=FORCE_HELP)
    p = sub.add_parser("update", help="upgrade dah, bring this workspace's files up to date, restart the tower")
    p.add_argument("--no-upgrade", action="store_true", help="only update the workspace with the installed version")
    p.add_argument("--dry-run", action="store_true",
                   help="show the upgrade command and package files changed in place; change nothing")
    p.add_argument("--no-restart", action="store_true", help="leave a running tower on the old code")
    p.add_argument("--all", action="store_true", help="every workspace registered on this machine")
    p = sub.add_parser("skill", help="install the global agent-hub-setup skill/command for your agents")
    ssub = p.add_subparsers(dest="sub", required=True)
    for name in ("install", "uninstall"):
        q = ssub.add_parser(name)
        q.add_argument("--runtime", action="append", choices=RUNTIMES, help="only this agent (repeatable)")
        q.add_argument("--yes", action="store_true", help="change the files (without it: show what would change)")
    p = sub.add_parser("uninstall", help="take agent-hub out of this workspace (shows the plan; --yes does it)")
    p.add_argument("--yes", action="store_true")
    p.add_argument("--purge", action="store_true", help="also delete .tower/ (config, lane files, extensions, history)")
    p.add_argument("--keep-lanes", action="store_true", help="leave running lane sessions open")
    p = sub.add_parser("guide", help="print the setup playbook, the extension guide, or a guide for reaching the board")
    p.add_argument("name", nargs="?", help="one of: " + ", ".join(guide_names()) + " (default: setup)")
    p = sub.add_parser("workspaces", help="workspaces with a tower on this machine (the board switches between them)")
    wsub = p.add_subparsers(dest="sub")
    wsub.add_parser("list")
    q = wsub.add_parser("remove")
    q.add_argument("slug")
    p = sub.add_parser("lane", help="list, add or remove lanes")
    lsub = p.add_subparsers(dest="sub", required=True)
    lsub.add_parser("list")
    q = lsub.add_parser("add")
    q.add_argument("id")
    q.add_argument("--runtime", required=True, help=f"{', '.join(RUNTIMES)}, or one an extension registers")
    q.add_argument("--worktree", action="store_true", help="work in a git worktree of its own (branch dah/ID; parallel session #N: dah/ID-N)")
    q.add_argument("--label")
    q.add_argument("--engine", help="the engine this lane belongs to (`dah engine list`); default: the implicit one")
    q.add_argument("--model")
    q.add_argument("--agent", help="run the role on one of your own agents (an OpenCode agent or a Claude --agent "
                                   "name); default: the agent you normally get")
    q = lsub.add_parser("remove")
    q.add_argument("id")
    p = sub.add_parser("engine", help="list, show or add engines (a set of lanes with its own skills and process)")
    gsub = p.add_subparsers(dest="sub", required=True)
    gsub.add_parser("list")
    q = gsub.add_parser("show")
    q.add_argument("id")
    q = gsub.add_parser("add")
    q.add_argument("id")
    q.add_argument("--label")
    q.add_argument("--dir", help="engine folder inside the workspace")
    q.add_argument("--library", help="pattern library markdown, path inside the workspace")
    q.add_argument("--skills", help="skills folder inside the workspace")
    q.add_argument("--map", help="hand-written engine.json, path inside the workspace")
    q.add_argument("--cap", help='usage cap: "tokens-day:N", or a name an extension registers in `caps`')
    q.add_argument("--from", dest="template", metavar="KIND", help="scaffold the engine from a template: blank, animation or marketing "
                   "(creates its library, skills with draft process and pattern cards, lanes and an engine review lane)")
    q.add_argument("--runtime", default="claude", help="runtime of the scaffolded lanes (with --from; default claude)")
    p = sub.add_parser("member", help="people who use the board")
    esub = p.add_subparsers(dest="sub", required=True)
    esub.add_parser("list")
    q = esub.add_parser("add")
    q.add_argument("name")
    q.add_argument("--role", choices=("owner", "member"), default="member")
    q.add_argument("--ident", help="identity the proxy sends (auth.mode=header), e.g. an email")
    q.add_argument("--token", action="store_true", help="issue a sign-in token (auth.mode=token)")
    q = esub.add_parser("remove")
    q.add_argument("name")
    p = sub.add_parser("prefs", help="hub: a person's board settings, changed on their chat request")
    fsub = p.add_subparsers(dest="sub", required=True)
    q = fsub.add_parser("show")
    q.add_argument("name", help="member")
    q = fsub.add_parser("set")
    q.add_argument("name", help="member")
    q.add_argument("pairs", nargs="+", metavar="NAME=VALUE",
                   help="first_tab=history, font=s|m|l, accent=green, hub.order=yours,asks, lanes.hidden=reports; "
                        "empty value = default")
    q = fsub.add_parser("reset")
    q.add_argument("name", help="member")
    return ap
